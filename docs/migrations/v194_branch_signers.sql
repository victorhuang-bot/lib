-- Additive PostgreSQL DDL for review. Not executed against any external DB.
-- The existing application bootstrap also creates this table idempotently.
BEGIN;
SELECT pg_advisory_xact_lock(194001);
CREATE TABLE IF NOT EXISTS branch_signers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  branch_id BIGINT NOT NULL REFERENCES branches(id),
  name TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  UNIQUE (branch_id, name)
);
COMMIT;
